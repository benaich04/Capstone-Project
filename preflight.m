function status = preflight()
%PREFLIGHT Identify missing MATLAB code, functions and toolboxes without hiding issues.
req={'blk1_txChannel','blk2_rx','blk3_tdoa','blk4_localize', ...
    'blk5_track','tdoaLocalize','tdoaModel','tdoaValidate', ...
    'tdoaOptions','tdoaWindowStep','tdoaWindowOptions', ...
    'tdoaStaticStep','config','checkIO', 'wlanNonHTConfig', ...
    'wlanWaveformGenerator','wlanSampleRate','wlanPacketDetect', ...
    'wlanLLTFDemodulate','wlanLLTFChannelEstimate', ...
    'wlanLLTFNoiseEstimate','wlanFieldIndices', ...
    'wlanSymbolTimingEstimate','wlanFineCFOEstimate', ...
    'wlanCoarseCFOEstimate','frequencyOffset'};
status=struct('functionNames',{req},'path',{cell(size(req))}, ...
    'found',false(size(req)));
for k=1:numel(req)
    status.path{k}=which(req{k});
    status.found(k)=~isempty(status.path{k});
    if status.found(k)
        fprintf('FOUND   %-27s %s\n',req{k},status.path{k});
    else
        fprintf(2,'MISSING %-27s\n',req{k});
    end
end
if ~all(status.found)
    error('preflight:DependencyMissing','Missing %d required dependencies.',sum(~status.found));
end
end
